export class GoalIcon {
    homeGoal: string;
    awayGoal: string;
    halfTimeHomeGoal: string;
    halfTimeAwayGoal: string;

    constructor(homeGoal: string,
        awayGoal: string,
        halfTimeHomeGoal: string,
        halfTimeAwayGoal: string){
            this.homeGoal = homeGoal;
            this.awayGoal = awayGoal;
            this.halfTimeHomeGoal = halfTimeHomeGoal;
            this.halfTimeAwayGoal = halfTimeAwayGoal;
        }
}